-- | Computes the exact Hilbert series expansion coefficients [h_0, h_1, ..., h_D]
-- for a complete intersection generated by polynomials of degrees [d_1, ..., d_m]
-- in n variables:
-- H_{R/I}(t) = \prod_{i=1}^m (1 - t^{d_i}) / (1 - t)^n.
completeIntersectionHilbertSeries :: Int -> [Int] -> Int -> [Integer]
completeIntersectionHilbertSeries numVars degrees maxDeg =
  [ computeH d | d <- [0 .. maxDeg] ]
  where
    seriesDenom = [ binom (k + numVars - 1) (numVars - 1) | k <- [0 .. maxDeg] ]

    multiplyFactor poly d =
      let shift = replicate d 0 ++ poly
          pPadded = poly ++ replicate d 0
      in zipWith (-) pPadded shift

    computeH d =
      sum [ let numC = if i < length numPoly then numPoly !! i else 0
                denC = seriesDenom !! (d - i)
            in numC * denC
          | i <- [0 .. min d (length numPoly - 1)]
          ]

    numPoly = foldl multiplyFactor [1] degrees

    binom n k
      | k < 0 || k > n = 0
      | k == 0 || k == n = 1
      | otherwise =
          let num = product [ toInteger (n - k + 1) .. toInteger n ]
              den = product [ 1 .. toInteger k ]
          in num `div` den

-- | Counts the number of standard monomials (monomials not in the initial ideal in(G))
-- of exact total degree d in n variables.
standardMonomialsCountInDegree :: Int -> Int -> [SparseMonomial] -> Int
standardMonomialsCountInDegree numVars targetDeg leadMonomials =
  let allMonomials = generateMonomialsOfDegree numVars targetDeg
      standardList = filter (\m -> not (any (\lm -> sparseDivides lm m) leadMonomials)) allMonomials
  in length standardList
  where
    generateMonomialsOfDegree 0 _ = []
    generateMonomialsOfDegree 1 d = [ makeMono [(0, d)] ]
    generateMonomialsOfDegree n d =
      [ makeMono ((0, k) : rest)
      | k <- [0 .. d]
      , monoRest <- generateMonomialsOfDegree (n - 1) (d - k)
      , let rest = [ (idx + 1, e) | (idx, e) <- toList monoRest ]
      ]

    makeMono pairs = SparseMonomial (Map.fromList (filter (\(_, e) -> e > 0) pairs))
    toList (SparseMonomial m) = Map.toList m

-- | Hilbert-Driven Buchberger Algorithm (Traverso 1996).
-- Given target quotient space dimensions [h_0, h_1, ..., h_D],
-- skips processing critical pairs in degree d once the number of standard monomials
-- matches the target Hilbert dimension h_d!
hilbertDrivenBuchberger :: forall c. (Eq c, Fractional c)
                        => Int                 -- ^ Number of variables
                        -> [Integer]           -- ^ Target Hilbert series [h_0, ..., h_D]
                        -> [Poly c]            -- ^ Generating polynomials
                        -> [Poly c]
hilbertDrivenBuchberger numVars targetH inputPolys =
  let nonZeroInputs = [ monicPoly p | p <- inputPolys, not (isZeroPoly p) ]
  in case nonZeroInputs of
       [] -> []
       [p] -> [p]
       (p0:rest) ->
         let initBasis = [p0]
             initSugars = [polyDegree p0]
             (fullBasis, _, initialQueue) =
               foldl installInitial (initBasis, initSugars, []) (zip [1 :: Int ..] rest)
             sortedQueue = sortPairsBySugar initialQueue
         in loop fullBasis sortedQueue
  where
    installInitial (currB, currS, currQ) (idx, p) =
      let sugarP = polyDegree p
          newQ = updatePairSetGebauerMoller currB currS p idx sugarP currQ
      in (currB ++ [p], currS ++ [sugarP], newQ)

    loop basis [] = basis
    loop basis (cp:cps) =
      let currentDeg = cpDegree cp
          targetDim = if currentDeg < length targetH then targetH !! currentDeg else 0
          currentLeadM = [ lm | p <- basis, Just lm <- [leadingMonomial p] ]
          currentStandardCount = toInteger (standardMonomialsCountInDegree numVars currentDeg currentLeadM)
      in if currentStandardCount <= targetDim && targetDim > 0
         then
           -- Hilbert dimension reached in this degree: all remaining pairs in this degree are redundant!
           let prunedQueue = filter (\p -> cpDegree p /= currentDeg) cps
           in loop basis prunedQueue
         else
           let p1 = cpPoly1 cp
               p2 = cpPoly2 cp
               sPoly = sPolynomial p1 p2
               remPoly = normalForm sPoly basis
           in if isZeroPoly remPoly
              then loop basis cps
              else
                let monicRem = monicPoly remPoly
                    newIdx = length basis
                    sugarRem = cpSugar cp
                    updatedQueue = updatePairSetGebauerMoller basis (map polyDegree basis) monicRem newIdx sugarRem cps
                    newBasis = basis ++ [monicRem]
                in loop newBasis updatedQueue
