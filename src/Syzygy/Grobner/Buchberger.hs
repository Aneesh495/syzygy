{-# LANGUAGE BangPatterns #-}
{-# LANGUAGE DeriveGeneric #-}
{-# LANGUAGE ScopedTypeVariables #-}

module Syzygy.Grobner.Buchberger
  ( buchberger
  , buchbergerWithStats
  , isGrobnerBasis
  , BuchbergerStats(..)
  , emptyStats
  ) where

import GHC.Generics (Generic)
import Syzygy.Monomial.Sparse (sparseCoprime)
import Syzygy.Polynomial.Base
  ( Poly(..)
  , isZeroPoly
  , leadingMonomial
  , polyDegree
  )
import Syzygy.Polynomial.Arithmetic (monicPoly)
import Syzygy.Polynomial.Division (normalForm)
import Syzygy.Grobner.SPolynomial
  ( CriticalPair(..)
  , sPolynomial
  )
import Syzygy.Grobner.Criteria
  ( updatePairSetGebauerMoller
  , sortPairsBySugar
  )

-- | Execution statistics collected during Buchberger's algorithm.
data BuchbergerStats = BuchbergerStats
  { bsPairsGenerated   :: !Int  -- ^ Total candidate critical pairs formed
  , bsCrit1Eliminated  :: !Int  -- ^ Pairs eliminated by Criterion 1 (coprime)
  , bsCrit2Eliminated  :: !Int  -- ^ Pairs eliminated by Criterion 2 (chain criterion)
  , bsCrit3Eliminated  :: !Int  -- ^ Pairs eliminated by Criterion 3 (F-criterion)
  , bsZeroReductions   :: !Int  -- ^ Pairs that reduced to 0 during division
  , bsNewGenerators    :: !Int  -- ^ Non-zero reductions added to the basis
  } deriving (Eq, Show, Generic)

-- | Initial empty statistics.
emptyStats :: BuchbergerStats
emptyStats = BuchbergerStats 0 0 0 0 0 0

-- | Buchberger's algorithm with Gebauer-Moller criteria and Giovini sugar strategy.
-- Computes a Groebner basis for the ideal generated by the input polynomials.
buchberger :: (Eq c, Fractional c) => [Poly c] -> [Poly c]
buchberger inputPolys = fst (buchbergerWithStats inputPolys)

-- | Buchberger's algorithm returning both the Groebner basis and performance telemetry.
buchbergerWithStats :: forall c. (Eq c, Fractional c)
                    => [Poly c] -> ([Poly c], BuchbergerStats)
buchbergerWithStats inputPolys =
  let nonZeroInputs = [ monicPoly p | p <- inputPolys, not (isZeroPoly p) ]
  in case nonZeroInputs of
       [] -> ([], emptyStats)
       [p] -> ([p], emptyStats)
       (p0:rest) ->
         let initBasis = [p0]
             initSugars = [polyDegree p0]
             (fullBasis, fullSugars, initialQueue) =
               foldl installInitial (initBasis, initSugars, []) (zip [1 :: Int ..] rest)
             sortedQueue = sortPairsBySugar initialQueue
         in loop fullBasis fullSugars sortedQueue emptyStats
  where
    installInitial (currB, currS, currQ) (idx, p) =
      let sugarP = polyDegree p
          newQ = updatePairSetGebauerMoller currB currS p idx sugarP currQ
      in (currB ++ [p], currS ++ [sugarP], newQ)

    loop !basis _ [] !stats = (basis, stats)
    loop !basis !sugars (cp:cps) !stats =
      let p1 = cpPoly1 cp
          p2 = cpPoly2 cp
          sPoly = sPolynomial p1 p2
          remPoly = normalForm sPoly basis
      in if isZeroPoly remPoly
         then
           let stats' = stats { bsZeroReductions = bsZeroReductions stats + 1 }
           in loop basis sugars cps stats'
         else
           let monicRem = monicPoly remPoly
               newIdx = length basis
               sugarRem = cpSugar cp
               updatedQueue = updatePairSetGebauerMoller basis sugars monicRem newIdx sugarRem cps
               newBasis = basis ++ [monicRem]
               newSugars = sugars ++ [sugarRem]
               stats' = stats { bsNewGenerators = bsNewGenerators stats + 1 }
           in loop newBasis newSugars updatedQueue stats'

-- | Verifies Buchberger's Criterion:
-- A set of polynomials G is a Groebner basis if and only if for all pairs (f_i, f_j) in G,
-- S(f_i, f_j) reduces to zero modulo G!
isGrobnerBasis :: forall c. (Eq c, Fractional c) => [Poly c] -> Bool
isGrobnerBasis basis
  | null basis || length basis == 1 = True
  | otherwise =
      let nonZeroBasis = filter (not . isZeroPoly) basis
          n = length nonZeroBasis
          pairs = [ (nonZeroBasis !! i, nonZeroBasis !! j)
                  | i <- [0 .. n - 1]
                  , j <- [i + 1 .. n - 1]
                  ]
      in all checkPair pairs
  where
    checkPair (p1, p2) =
      case (leadingMonomial p1, leadingMonomial p2) of
        (Just m1, Just m2)
          | sparseCoprime m1 m2 -> True  -- Criterion 1: guaranteed zero reduction!
          | otherwise ->
              let sPoly = sPolynomial p1 p2
                  remPoly = normalForm sPoly basis
              in isZeroPoly remPoly
        _ -> True
